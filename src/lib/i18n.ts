export type TranslationKey = keyof typeof translations;

/**
 * Translate a key to the current language.
 * Falls back to Arabic if the key is not found.
 */
export function t(key: TranslationKey, lang?: Lang): string {
  const l = lang ?? getStoredLang();
  const entry = translations[key];
  if (!entry) return key;
  return entry[l] ?? entry["ar"] ?? key;
}

/**
 * Create a translator bound to a specific language.
 * Useful inside components that already know the language.
 */
export function createTranslator(lang: Lang) {
  return (key: TranslationKey) => t(key, lang);
}
